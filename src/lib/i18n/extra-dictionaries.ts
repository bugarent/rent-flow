export const extraDictionaries: Partial<Record<Locale, DeepPartial<Dictionary>>> = {
  es,
  it,
  nl,
  tr,
  zh,
  ko,
  th,
};

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return !!value && typeof value === "object" && !Array.isArray(value);
}

function deepFill<T>(base: T, patch: unknown): T {
  if (Array.isArray(base)) {
    return (Array.isArray(patch) && patch.length ? patch : base) as T;
  }
  if (isPlainObject(base)) {
    const over = isPlainObject(patch) ? patch : {};
    const out: Record<string, unknown> = {};
    for (const key of Object.keys(base)) {
      out[key] = deepFill((base as Record<string, unknown>)[key], over[key]);
    }
    return out as T;
  }
  if (typeof patch === "string" && patch.trim()) return patch as T;
  return base;
}

/** Use a full dictionary when it exists; otherwise overlay the extra locale on English. */
export function withExtraDictionary<T>(english: T, locale: Locale, exact: T | undefined): T {
  if (exact) return exact;
  const extra = extraDictionaries[locale];
  return extra ? deepFill(english, extra) : english;
}
