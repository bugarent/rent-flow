type CheckoutCopyBase = Omit<
  CheckoutCopy,
  | "seats"
  | "doors"
  | "forDays"
  | "excellentReviews"
  | "lowDeposit"
  | "totalCost"
  | "eachPerRental"
  | "totalForDays"
  | "siteServiceFee"
  | "linePerDays"
  | "deliveryPickupAt"
  | "deliveryReturnAt"
> & {
  seatsTemplate: string;
  doorsTemplate: string;
  forDaysTemplate: string;
  excellentReviewsTemplate: string;
  lowDepositTemplate: string;
  totalCostTemplate: string;
  eachPerRentalTemplate: string;
  totalForDaysTemplate: string;
  siteServiceFeeTemplate: string;
  linePerDaysTemplate: string;
  deliveryPickupAtTemplate: string;
  deliveryReturnAtTemplate: string;
};

function bind(base: CheckoutCopyBase): CheckoutCopy {
  const {
    seatsTemplate,
    doorsTemplate,
    forDaysTemplate,
    excellentReviewsTemplate,
    lowDepositTemplate,
    totalCostTemplate,
    eachPerRentalTemplate,
    totalForDaysTemplate,
    siteServiceFeeTemplate,
    linePerDaysTemplate,
    deliveryPickupAtTemplate,
    deliveryReturnAtTemplate,
    ...rest
  } = base;
  return {
    ...rest,
    seats: (n) => seatsTemplate.replace("{n}", String(n)),
    doors: (n) => doorsTemplate.replace("{n}", String(n)),
    forDays: (n) => forDaysTemplate.replace("{n}", String(n)),
    excellentReviews: (avg, count) =>
      excellentReviewsTemplate.replace("{avg}", avg).replace("{count}", String(count)),
    lowDeposit: (label) => lowDepositTemplate.replace("{label}", label),
    totalCost: (price) => totalCostTemplate.replace("{price}", price),
    eachPerRental: (price) => eachPerRentalTemplate.replace("{price}", price),
    totalForDays: (n) => totalForDaysTemplate.replace("{n}", String(n)),
    siteServiceFee: (percent) => siteServiceFeeTemplate.replace("{percent}", String(percent)),
    linePerDays: (price, n) =>
      linePerDaysTemplate.replace("{price}", price).replace("{n}", String(n)),
    deliveryPickupAt: (place) => deliveryPickupAtTemplate.replace("{place}", place),
    deliveryReturnAt: (place) => deliveryReturnAtTemplate.replace("{place}", place),
  };
}

